import assert from "node:assert/strict";
import { execSync } from "node:child_process";
import { readFileSync } from "node:fs";

execSync("rm -rf .discipline-definition-test-build && npx tsc lib/disciplines.ts --ignoreConfig --module NodeNext --moduleResolution NodeNext --target ES2022 --outDir .discipline-definition-test-build --skipLibCheck", { stdio: "inherit" });
const d = await import("../.discipline-definition-test-build/disciplines.js");
const expected = ["Compak Sporting", "Kompakt leirduesti", "Sporttrap", "Leirduesti", "FITASC Sporting", "Sporting", "English Sporting", "Jegertrap / Nordisk trap", "Trap", "Skeet", "Other"];
assert.deepEqual(Array.from(d.DISCIPLINE_DEFINITIONS, (definition) => definition.value), expected);
assert.deepEqual(Array.from(d.DISCIPLINE_OPTIONS), expected);
assert.equal(new Set(d.DISCIPLINE_OPTIONS).size, expected.length);
assert.equal(d.canonicalizeDiscipline("Compak Sporting"), "Compak Sporting");
assert.equal(d.canonicalizeDiscipline("  cOmPaK sPoRtInG "), "Compak Sporting");
assert.equal(d.canonicalizeDiscipline("Engelsk sporting"), "English Sporting");
assert.equal(d.canonicalizeDiscipline("  Local Pool Shoot  "), "Local Pool Shoot");
assert.equal(d.canonicalizeDiscipline("  "), "");
const engines = Object.fromEntries(expected.map((value) => [value, d.disciplineScoreSheetEngine(value)]));
assert.equal(engines["Compak Sporting"], "compak");
for (const value of expected.slice(1)) assert.equal(engines[value], "generic", `${value} remains generic`);
assert.equal(d.isCompactDiscipline("Kompakt leirduesti"), true, "legacy compact classification remains broad");
assert.equal(d.usesCompakScoreSheetEngine("Kompakt leirduesti"), false, "Kompakt leirduesti never loads the Compak engine");
assert.deepEqual([d.getDisciplineDefinition("Compak Sporting").areaSingular, d.getDisciplineDefinition("Compak Sporting").areaPlural], ["Plate", "Plates"]);
assert.deepEqual([d.getDisciplineDefinition("Leirduesti").areaSingular, d.getDisciplineDefinition("Leirduesti").areaPlural], ["Post", "Posts"]);
assert.deepEqual([d.getDisciplineDefinition("Sporting").areaSingular, d.getDisciplineDefinition("Sporting").areaPlural], ["Stand", "Stands"]);
const fallback = d.getDisciplineDefinition(" Local Pool Shoot ");
assert.deepEqual([fallback.value, fallback.label, fallback.scoreSheetEngine, fallback.areaSingular, fallback.areaPlural, fallback.quickStartKey], ["Local Pool Shoot", "Local Pool Shoot", "generic", "Stand", "Stands", undefined]);
assert.equal(d.getDisciplineDefinition("Compak Sporting").quickStartKey, "compak");
assert.equal(d.getDisciplineDefinition("Leirduesti").quickStartKey, "leirduesti");
for (const value of ["Trap", "Skeet", "FITASC Sporting", "Sporting"]) assert.equal(d.getDisciplineDefinition(value).quickStartKey, undefined);
assert.equal(d.leirdueTitleDisciplineHints("Kompaktsti cup"), "Kompakt leirduesti");
assert.equal(d.leirdueTitleDisciplineHints("Compact leirduesti open"), "Kompakt leirduesti");
assert.equal(d.leirdueTitleDisciplineHints("Compak Sporting Grand Prix"), "Compak Sporting");
assert.equal(d.leirdueTitleDisciplineHints("Local pool shoot"), null);
const profile = readFileSync("app/components/ShooterProfileForm.tsx", "utf8");
const editor = readFileSync("app/components/scoreSheets/ScoreSheetEditor.tsx", "utf8");
assert.match(profile, /DISCIPLINE_OPTIONS/);
assert.match(editor, /DISCIPLINE_OPTIONS/);
assert.match(editor, /usesCompakScoreSheetEngine\(draft\.discipline\)/);
assert.match(editor, /getDisciplineDefinition\(discipline\)/);
assert.doesNotMatch(editor, /function isCompakSporting/);
execSync("rm -rf .discipline-definition-test-build");
console.log("Authoritative discipline definitions, fallbacks, terminology, presets, and engine classification tests passed.");
